CREATE OR REPLACE FUNCTION ext.county_sort_order(IN p_county TEXT)
RETURNS INTEGER
AS
$BODY$
BEGIN
    IF p_county IS NULL THEN
        RETURN 99;
    END IF;
    RETURN
    CASE UPPER(TRIM(p_county))
        WHEN 'ESCAMBIA' THEN 0
        WHEN 'SANTA ROSA' THEN 1
        WHEN 'OKALOOSA' THEN 2
        WHEN 'WALTON' THEN 3
        WHEN 'HOLMES' THEN 4
        WHEN 'BAY' THEN 5
        WHEN 'WASHINGTON' THEN 6
        WHEN 'JACKSON' THEN 7
        WHEN 'CALHOUN' THEN 8
        WHEN 'GULF' THEN 9
        WHEN 'LIBERTY' THEN 10
        WHEN 'FRANKLIN' THEN 11
        WHEN 'GADSDEN' THEN 12
        WHEN 'LEON' THEN 13
        WHEN 'WAKULLA' THEN 14
        WHEN 'JEFFERSON' THEN 15
        WHEN 'TAYLOR' THEN 16
        WHEN 'DIXIE' THEN 17
        WHEN 'MADISON' THEN 18
        WHEN 'HAMILTON' THEN 19
        WHEN 'SUWANNEE' THEN 20
        WHEN 'LAFAYETTE' THEN 21
        WHEN 'COLUMBIA' THEN 22
        WHEN 'UNION' THEN 23
        WHEN 'BRADFORD' THEN 24
        WHEN 'GILCHRIST' THEN 25
        WHEN 'LEVY' THEN 26
        WHEN 'ALACHUA' THEN 27
        WHEN 'MARION' THEN 28
        WHEN 'CITRUS' THEN 29
        WHEN 'SUMTER' THEN 30
        WHEN 'HERNANDO' THEN 31
        WHEN 'PASCO' THEN 32
        WHEN 'PINELLAS' THEN 33
        WHEN 'HILLSBOROUGH' THEN 34
        WHEN 'MANATEE' THEN 35
        WHEN 'HARDEE' THEN 36
        WHEN 'POLK' THEN 37
        WHEN 'HIGHLANDS' THEN 38
        WHEN 'DESOTO' THEN 39
        WHEN 'CHARLOTTE' THEN 40
        WHEN 'SARASOTA' THEN 41
        WHEN 'GLADES' THEN 42
        WHEN 'LEE' THEN 43
        WHEN 'HENDRY' THEN 44
        WHEN 'OKEECHOBEE' THEN 45
        WHEN 'OSCEOLA' THEN 46
        WHEN 'ORANGE' THEN 47
        WHEN 'SEMINOLE' THEN 48
        WHEN 'LAKE' THEN 49
        WHEN 'VOLUSIA' THEN 50
        WHEN 'PUTNAM' THEN 51
        WHEN 'FLAGLER' THEN 52
        WHEN 'ST. JOHNS' THEN 53
        WHEN 'ST JOHNS' THEN 53
        WHEN 'CLAY' THEN 54
        WHEN 'DUVAL' THEN 55
        WHEN 'BAKER' THEN 56
        WHEN 'NASSAU' THEN 57
        WHEN 'INDIAN RIVER' THEN 58
        WHEN 'ST. LUCIE' THEN 59
        WHEN 'ST LUCIE' THEN 59
        WHEN 'MARTIN' THEN 60
        WHEN 'PALM BEACH' THEN 61
        WHEN 'BROWARD' THEN 62
        WHEN 'MIAMI-DADE' THEN 63
        WHEN 'MIAMI DADE' THEN 63
        WHEN 'COLLIER' THEN 64
        WHEN 'MONROE' THEN 65
        WHEN 'BREVARD' THEN 66
        ELSE 99
    END;
END;
$BODY$
LANGUAGE  plpgsql;

